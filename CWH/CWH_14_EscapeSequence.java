public class CWH_14_EscapeSequence {
    public static void main(String[] args) {
        System.out.println("I am a good boy \t Escape Sequence");
        System.out.println("I am a good boy \b Escape Sequence");
        System.out.println("I am a good boy \n Escape Sequence");
        System.out.println("I am a good boy \r Escape Sequence");
        System.out.println("I am a good boy \f Escape Sequence");
        System.out.println("I am a good boy \' Escape Sequence");
        System.out.println("I am a good boy \" Escape Sequence");
        System.out.println("I am a good boy \\ Escape Sequence");
    }
    
}
